// Hacer un programa que recibe dos números, calcular y
// mostrar la resta del primer número por segundo
#include <iostream>
using namespace std;
int main() {
    float x,y,R;
    cout<<"Ingrese dos numeros: "<<endl;
    cin>>x>>y;
    R=x+y;
    cout<<"Resultado:"<<R<<endl;
    return 0;
}
